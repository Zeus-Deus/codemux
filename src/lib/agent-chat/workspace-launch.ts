import type { ToolCallItem } from "./types";

export function isWorkspaceLaunchToolName(name: string): boolean {
  return name === "workspace_launch" || name.endsWith("__workspace_launch");
}

function record(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function parse(value: unknown): unknown {
  if (typeof value !== "string") return value;
  try { return JSON.parse(value); } catch { return null; }
}

export function workspaceLaunchInput(toolName: string, input: unknown): Record<string, unknown> | null {
  if (toolName === "dynamicToolCall" && record(input) && isWorkspaceLaunchToolName(String(input.tool))) {
    const args = parse(input.arguments);
    return record(args) ? args : null;
  }
  return isWorkspaceLaunchToolName(toolName) && record(input) ? input : null;
}

export function isWorkspaceLaunchCall(item: ToolCallItem): boolean {
  return workspaceLaunchInput(item.tool_name, item.input) !== null;
}

function startingBranch(content: unknown): string | null {
  const value = parse(content);
  if (Array.isArray(value)) {
    for (const block of value) {
      const branch = startingBranch(block);
      if (branch) return branch;
    }
    return null;
  }
  if (!record(value)) return null;
  if (value.status === "starting" && typeof value.branch === "string") return value.branch;
  return startingBranch(value.contentItems ?? value.content ?? value.text);
}

/** The accepted branch may be generated by the host rather than supplied. */
export function workspaceLaunchBranch(item: ToolCallItem): string | null {
  const accepted = startingBranch(item.result_content);
  if (accepted) return accepted;
  const branch = workspaceLaunchInput(item.tool_name, item.input)?.branch;
  return typeof branch === "string" ? branch : null;
}
